<?php
// File Location: api/dashboard/submit_report.php
ob_start(); 
session_start();
header('Content-Type: application/json');

// Strips ALL HTML tags (not just <script>) - the safe default for a plain-text
// field like a damage report description, which should never contain markup at
// all. This is stronger than only blocking <script>, which is easy to bypass
// with other tags (<img onerror=...>, <svg onload=...>, etc.).
function sanitizeHtmlInput($input) {
    return strip_tags(trim($input));
}

try {
    require_once '../config/db_connection.php';

    // Returned rather than thrown, with a real HTTP status and a machine-readable
    // code: safeErrorMessage() in the catch below replaces any thrown text with a
    // generic "A server error occurred", so a client replaying a queued report
    // could not tell an expired session from a database fault - and would have to
    // guess whether to keep the report or discard it. This runs before
    // begin_transaction(), so there is nothing to roll back.
    $farmer_id = $_SESSION['user_id'] ?? $_SESSION['User_ID'] ?? $_SESSION['id'] ?? null;
    if (!$farmer_id) {
        if (ob_get_length()) ob_clean();
        http_response_code(401);
        echo json_encode([
            'status'  => 'error',
            'code'    => 'auth',
            'message' => 'Session expired. Please log in again.'
        ]);
        exit;
    }

    if (empty($_POST['damage_type']) || empty($_POST['severity'])) {
        if (ob_get_length()) ob_clean();
        echo json_encode(['status' => 'error', 'message' => 'Damage type and severity are required.']);
        exit;
    }

    $conn->begin_transaction();
    
    // Sanitize incoming text data
    $report_id     = !empty($_POST['id']) ? (int)$_POST['id'] : null;
    $location_id   = !empty($_POST['location_id']) ? (int)$_POST['location_id'] : null;
    $crop_id       = !empty($_POST['crop_id']) ? (int)$_POST['crop_id'] : null; 
    $type_id       = !empty($_POST['type_id']) ? (int)$_POST['type_id'] : null;
    $planting_date = !empty($_POST['planting_date']) ? $_POST['planting_date'] : null;
    $area          = !empty($_POST['area']) ? (float)$_POST['area'] : 0.00;
    if ($area <= 0) {
        echo json_encode(["status" => "error", "message" => "Affected area must be greater than 0."]);
        exit;
    }
    $damage_type   = sanitizeHtmlInput($_POST['damage_type']);
    $severity      = sanitizeHtmlInput($_POST['severity']);
    $description   = sanitizeHtmlInput($_POST['description'] ?? '');

    // Idempotency key generated by the client (assets/js/offline_queue.js). A
    // report queued offline can be replayed after its response was lost in
    // transit, which would otherwise commit a SECOND damage_report plus two more
    // admin_notification rows. Also sent on ordinary online submissions, which
    // makes an impatient double-tap of Submit harmless too.
    $client_token = preg_replace('/[^A-Za-z0-9\-]/', '', (string)($_POST['client_token'] ?? ''));
    $client_token = ($client_token === '') ? null : substr($client_token, 0, 40);

    // Fast path: this token already produced a report, so the earlier attempt
    // did land and only its reply went missing. Report success so the client
    // clears it from the queue instead of sending it again forever. Nothing has
    // been written yet at this point, so the rollback is a formality.
    if (!$report_id && $client_token) {
        $dupStmt = $conn->prepare("SELECT Damage_Report_ID FROM damage_report WHERE Client_Token = ? AND Farmer_ID = ?");
        $dupStmt->bind_param("si", $client_token, $farmer_id);
        $dupStmt->execute();
        $dupRow = $dupStmt->get_result()->fetch_assoc();
        $dupStmt->close();

        if ($dupRow) {
            $conn->rollback();
            if (ob_get_length()) ob_clean();
            echo json_encode([
                'status'    => 'success',
                'duplicate' => true,
                'report_id' => (int)$dupRow['Damage_Report_ID'],
                'message'   => 'This report was already submitted.'
            ]);
            exit;
        }
    }

    // $report_id comes straight from the request. The report UPDATE further down
    // is scoped with "AND Farmer_ID = ?" so it can't touch someone else's row,
    // but its affected_rows was never checked - execution carried on into the
    // image handling below, which scopes deletes image -> report and NOT
    // image -> report -> farmer. So passing another farmer's report id let you
    // unlink their evidence photos from disk, and upload photos onto their
    // report. Verify ownership once, here, before anything uses this id.
    if ($report_id) {
        $ownCheck = $conn->prepare("SELECT Status FROM damage_report WHERE Damage_Report_ID = ? AND Farmer_ID = ?");
        $ownCheck->bind_param("ii", $report_id, $farmer_id);
        $ownCheck->execute();
        $ownRow = $ownCheck->get_result()->fetch_assoc();
        $ownCheck->close();

        if (!$ownRow) {
            throw new Exception('Report not found.');
        }
        // A farmer may only edit a report while it is still Pending - before the
        // MAO office has validated it. After that the report, and in particular
        // the technician's severity assessment, must not be editable from the
        // farmer side. The form only shows Edit on Pending rows; this is the
        // guard that actually holds against a stale tab or a crafted request.
        if ($ownRow['Status'] !== 'Pending') {
            $conn->rollback();
            if (ob_get_length()) ob_clean();
            echo json_encode(['status' => 'error', 'message' => 'This report has already been reviewed and can no longer be edited.']);
            exit;
        }
    }

    // The selected farm must belong to this farmer and still be active, and the
    // affected area can't be larger than the farm's own size. The form enforces
    // all of this, but a crafted request could send any location_id or area.
    if ($location_id) {
        $farmStmt = $conn->prepare("SELECT Area_Size, Is_Archived FROM farm_location WHERE Location_ID = ? AND Farmer_ID = ?");
        $farmStmt->bind_param("ii", $location_id, $farmer_id);
        $farmStmt->execute();
        $farm = $farmStmt->get_result()->fetch_assoc();
        $farmStmt->close();

        if (!$farm) {
            $conn->rollback();
            if (ob_get_length()) ob_clean();
            echo json_encode(['status' => 'error', 'message' => 'The selected farm was not found for your account.']);
            exit;
        }
        if ((int)($farm['Is_Archived'] ?? 0) === 1) {
            $conn->rollback();
            if (ob_get_length()) ob_clean();
            echo json_encode(['status' => 'error', 'message' => 'That farm has been archived and can no longer be used for a report.']);
            exit;
        }
        if ($farm['Area_Size'] !== null && $area > (float)$farm['Area_Size']) {
            $conn->rollback();
            if (ob_get_length()) ob_clean();
            echo json_encode(['status' => 'error', 'message' => 'The affected area cannot be larger than the farm size (' . (float)$farm['Area_Size'] . ' ha).']);
            exit;
        }
    }

    // RSBSA gate for NEW reports: the farmer must have a valid RSBSA on file,
    // same rule as api/farmer/check_rsbsa.php. The form checks this first, but
    // the server must never accept a report from a farmer who has none.
    if (!$report_id) {
        $rsbaStmt = $conn->prepare("SELECT RSBA_No FROM users WHERE User_ID = ?");
        $rsbaStmt->bind_param("i", $farmer_id);
        $rsbaStmt->execute();
        $rsba = $rsbaStmt->get_result()->fetch_assoc()['RSBA_No'] ?? '';
        $rsbaStmt->close();
        if (empty($rsba) || !preg_match('/^\d{3}-\d{4}-\d{5}$/', $rsba)) {
            $conn->rollback();
            if (ob_get_length()) ob_clean();
            echo json_encode(['status' => 'error', 'message' => 'A valid RSBSA number is required in your profile before you can submit a damage report.']);
            exit;
        }
    }

    // Find-or-create the actual `crop` row for this Farmer + Location + Type combo.
    // The dropdown now sends a Type_ID (from the farm's own registration), not a
    // guaranteed-to-exist Crop_ID — so we resolve it into a real Crop_ID here.
    if ($type_id && $location_id) {
        $findCrop = $conn->prepare("SELECT Crop_ID FROM crop WHERE Farmer_ID = ? AND Location_ID = ? AND Type_ID = ? LIMIT 1");
        $findCrop->bind_param("iii", $farmer_id, $location_id, $type_id);
        $findCrop->execute();
        $existing = $findCrop->get_result()->fetch_assoc();
        $findCrop->close();

        if ($existing) {
            $crop_id = $existing['Crop_ID'];
            $sql_crop = "UPDATE crop SET Planting_Date = ?, Area_Hectares = ? WHERE Crop_ID = ?";
            $stmt_crop = $conn->prepare($sql_crop);
            $stmt_crop->bind_param("sdi", $planting_date, $area, $crop_id);
            $stmt_crop->execute();
        } else {
            $cropNameStmt = $conn->prepare("SELECT Crop_Name FROM crop_type WHERE Type_ID = ?");
            $cropNameStmt->bind_param("i", $type_id);
            $cropNameStmt->execute();
            $crop_name = $cropNameStmt->get_result()->fetch_assoc()['Crop_Name'] ?? 'Registered Crop';
            $cropNameStmt->close();

            $insertCrop = $conn->prepare("INSERT INTO crop (Crop_Name, Type_ID, Planting_Date, Area_Hectares, Farmer_ID, Location_ID) VALUES (?, ?, ?, ?, ?, ?)");
            $insertCrop->bind_param("sisdii", $crop_name, $type_id, $planting_date, $area, $farmer_id, $location_id);
            $insertCrop->execute();
            $crop_id = $insertCrop->insert_id;
            $insertCrop->close();
        }
    }

    // 4. INSERT OR UPDATE (FIXED: Added Type_ID to INSERT)
    if ($report_id) {
        // Affected_Area is stored on the report itself, not read from the shared
        // crop row - so each report keeps the area it was filed with and a later
        // report (or a farm edit) can never rewrite an earlier report's loss.
        $sql_report = "UPDATE damage_report
                       SET Location_ID = ?, Crop_ID = ?, Affected_Area = ?, Damage_Type = ?, Damage_Severity = ?, Description = ?
                       WHERE Damage_Report_ID = ? AND Farmer_ID = ?";
        $stmt_report = $conn->prepare($sql_report);
        $stmt_report->bind_param("iidsssii", $location_id, $crop_id, $area, $damage_type, $severity, $description, $report_id, $farmer_id);
        $stmt_report->execute();
        $success_message = 'Report successfully updated!';

        // Delete only the specific photos the farmer explicitly removed. Scoping
        // here is image -> report only; what makes that safe is the ownership
        // check performed on $report_id near the top of this file, which
        // guarantees this report belongs to the session farmer before we get
        // here. (That check is why this comment is now accurate - it previously
        // claimed a re-check that did not exist.)
        if (!empty($_POST['removed_image_ids']) && is_array($_POST['removed_image_ids'])) {
            foreach ($_POST['removed_image_ids'] as $imgId) {
                $imgId = (int)$imgId;
                $delStmt = $conn->prepare("SELECT Image_Path FROM damage_report_images WHERE Image_ID = ? AND Damage_Report_ID = ?");
                $delStmt->bind_param("ii", $imgId, $report_id);
                $delStmt->execute();
                $imgRow = $delStmt->get_result()->fetch_assoc();
                $delStmt->close();
                if ($imgRow) {
                    $filePath = '../../' . $imgRow['Image_Path'];
                    if (file_exists($filePath)) unlink($filePath);
                    $removeStmt = $conn->prepare("DELETE FROM damage_report_images WHERE Image_ID = ?");
                    $removeStmt->bind_param("i", $imgId);
                    $removeStmt->execute();
                    $removeStmt->close();
                }
            }
        }
    } else {
        // FIXED: Included Type_ID here so it isn't empty
        $sql_report = "INSERT INTO damage_report (Farmer_ID, Location_ID, Crop_ID, Affected_Area, Damage_Type, Damage_Severity, Farmer_Reported_Severity, Description, Client_Token, Status)
                       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'Pending')";
        $stmt_report = $conn->prepare($sql_report);
        // Affected_Area is stored per-report (see the UPDATE branch above for why).
        // Farmer_Reported_Severity is a permanent snapshot of what the farmer originally
        // reported. Damage_Severity gets overwritten once a technician inspects the farm,
        // so without this the farmer's original number would be lost forever.
        $stmt_report->bind_param("iiidsssss", $farmer_id, $location_id, $crop_id, $area, $damage_type, $severity, $severity, $description, $client_token);

        if (!$stmt_report->execute()) {
            // Backstop for the genuine race the SELECT above cannot catch: two
            // replays of the same queued report in flight at once, where both
            // passed the duplicate check before either had committed. The unique
            // index on Client_Token stops the second one here (errno 1062).
            if ($conn->errno === 1062 || $stmt_report->errno === 1062) {
                $stmt_report->close();
                $conn->rollback();   // also unwinds the crop find-or-create above

                $againStmt = $conn->prepare("SELECT Damage_Report_ID FROM damage_report WHERE Client_Token = ? AND Farmer_ID = ?");
                $againStmt->bind_param("si", $client_token, $farmer_id);
                $againStmt->execute();
                $againRow = $againStmt->get_result()->fetch_assoc();
                $againStmt->close();

                if (ob_get_length()) ob_clean();
                echo json_encode([
                    'status'    => 'success',
                    'duplicate' => true,
                    'report_id' => $againRow ? (int)$againRow['Damage_Report_ID'] : null,
                    'message'   => 'This report was already submitted.'
                ]);
                exit;
            }
            throw new Exception("Insert failed: " . $stmt_report->error);
        }
        $report_id = $conn->insert_id;
        $success_message = 'Report submitted successfully!';

        // Notify Admin staff of the new report
        $farmer_name = $_SESSION['Fullname'] ?? 'A farmer';
        $admin_msg = "New damage report (#REP-{$report_id}) submitted by {$farmer_name} — awaiting review.";
        $stmt_admin_notif = $conn->prepare("INSERT INTO admin_notification (Target_Role, Message, Related_Report_ID) VALUES ('Admin', ?, ?)");
        $stmt_admin_notif->bind_param("si", $admin_msg, $report_id);
        $stmt_admin_notif->execute();
        $stmt_admin_notif->close();

        // Notify MAO staff too — they're the ones who validate Pending reports
        $mao_msg = "New damage report (#REP-{$report_id}) submitted by {$farmer_name} — needs your validation.";
        $mao_redirect = 'report_management.html';
        $stmt_mao_notif = $conn->prepare("INSERT INTO admin_notification (Target_Role, Message, Related_Report_ID, Redirect_URL) VALUES ('MAO', ?, ?, ?)");
        $stmt_mao_notif->bind_param("sis", $mao_msg, $report_id, $mao_redirect);
        $stmt_mao_notif->execute();
        $stmt_mao_notif->close();
    }

    // 5. PROCESS IMAGE UPLOADS
    $skipped_uploads = 0;
    if (isset($_FILES['images']) && is_array($_FILES['images']['name'])) {
        $upload_dir = '../../uploads/reports/'; 
        if (!is_dir($upload_dir)) mkdir($upload_dir, 0777, true);

        for ($i = 0; $i < count($_FILES['images']['name']); $i++) {
            if ($_FILES['images']['error'][$i] === UPLOAD_ERR_OK) {
                $file_ext = strtolower(pathinfo($_FILES['images']['name'][$i], PATHINFO_EXTENSION));
                $isValidImage = in_array($file_ext, ['jpg', 'jpeg', 'png']) && (getimagesize($_FILES['images']['tmp_name'][$i]) !== false);
                if ($isValidImage) {
                    $new_file_name = 'rep_' . $report_id . '_' . uniqid() . '.' . $file_ext;
                    if (move_uploaded_file($_FILES['images']['tmp_name'][$i], $upload_dir . $new_file_name)) {
                        $db_path = 'uploads/reports/' . $new_file_name;
                        $lat = !empty($_POST["geo_lat_$i"]) ? (float)$_POST["geo_lat_$i"] : null;
                        $lng = !empty($_POST["geo_lng_$i"]) ? (float)$_POST["geo_lng_$i"] : null;
                        
                        $stmt_img = $conn->prepare("INSERT INTO damage_report_images (Damage_Report_ID, Image_Path, geo_lat, geo_lng) VALUES (?, ?, ?, ?)");
                        $stmt_img->bind_param("isdd", $report_id, $db_path, $lat, $lng);
                        $stmt_img->execute();
                    } else {
                        $skipped_uploads++;
                    }
                } else {
                    $skipped_uploads++;
                }
            } else {
                // UPLOAD_ERR_INI_SIZE (or similar) - the file was rejected before it even
                // reached this script, most commonly because it exceeded upload_max_filesize.
                $skipped_uploads++;
            }
        }
    }

    $conn->commit();
    if ($skipped_uploads > 0) {
        $success_message .= ' (' . $skipped_uploads . ' photo' . ($skipped_uploads > 1 ? 's' : '') . ' could not be uploaded and were skipped - please check file size and try again if needed.)';
    }
    echo json_encode(['status' => 'success', 'message' => $success_message]);

} catch (Exception $e) {
    if (isset($conn)) $conn->rollback();
    if (ob_get_length()) ob_clean();
    echo json_encode(['status' => 'error', 'message' => safeErrorMessage($e)]);
}
?>